"""KiCad application helper: construct a four-layer placement draft from circuit.json.
Run via tools/build.py under base conda; pcbnew uses KiCad's own Python ABI.
Routing and fabrication release are deliberately not generated by this helper.
"""
import pcbnew as k
from pathlib import Path
import json, uuid, os, re
ROOT=Path(__file__).resolve().parents[1]
LIB=Path(os.environ.get('KICAD_FOOTPRINT_DIR','/Volumes/KiCad/KiCad/KiCad.app/Contents/SharedSupport/footprints'))
d=json.loads((ROOT/'hardware/circuit.json').read_text());b=k.BOARD();b.SetCopperLayerCount(4)
mm=k.FromMM;v=lambda x,y:k.VECTOR2I(mm(x),mm(y))
nets={}
for name in sorted({pin['net'] for p in d['parts'] for pin in p['pins'] if pin['net']}):
 n=k.NETINFO_ITEM(b,name);b.Add(n);nets[name]=n
report={'status':'UNROUTED_REVIEW_DRAFT','missing_pads':[],'unmapped_pads':[],'footprints':[]}
for p in d['parts']:
 lib,fp=p['footprint'].split(':');f=k.FootprintLoad(str(LIB/(lib+'.pretty')),fp)
 if not f:raise RuntimeError('Missing footprint '+p['footprint'])
 f.SetReference(p['ref']);f.SetValue(p['value']);f.SetPosition(v(p['x'],p['y']));f.SetOrientationDegrees(p['rot'])
 f.SetPath(k.KIID_PATH('/'+str(uuid.uuid5(uuid.NAMESPACE_URL,'https://github.com/jvierine/prnboard/schematic'))+'/'+str(uuid.uuid5(uuid.NAMESPACE_URL,'https://github.com/jvierine/prnboard/inst/'+p['ref']))))
 pins={a['n']:a for a in p['pins']};pads={a.GetNumber() for a in f.Pads() if a.GetNumber()}
 for n in pins.keys()-pads:report['missing_pads'].append({'ref':p['ref'],'pin':n})
 for n in pads-pins.keys():report['unmapped_pads'].append({'ref':p['ref'],'pad':n})
 for pad in f.Pads():
  pin=pins.get(pad.GetNumber())
  if pin and pin['net']:pad.SetNet(nets[pin['net']])
 f.Reference().SetTextSize(v(.7,.7));f.Reference().SetLayer(k.F_Fab);f.Value().SetVisible(False);b.Add(f)
 # Include exact loaded footprint locally so the review does not depend on global libraries.
 local=ROOT/'hardware/PRNboard.pretty';local.mkdir(exist_ok=True)
 text=(LIB/(lib+'.pretty')/(fp+'.kicad_mod')).read_text()
 text=re.sub(r'\(footprint \"[^\"]+\"', '(footprint \"'+p['ref']+'\"',text,count=1)
 (local/(p['ref']+'.kicad_mod')).write_text(text)
 f.SetFPID(k.LIB_ID('PRNboard',p['ref']))
 report['footprints'].append({'ref':p['ref'],'library':p['footprint'],'physical_pads':len(list(f.Pads()))})
for a,z in [((0,0),(95,0)),((95,0),(95,85)),((95,85),(0,85)),((0,85),(0,0))]:
 shape=k.PCB_SHAPE();shape.SetShape(k.SHAPE_T_SEGMENT);shape.SetLayer(k.Edge_Cuts);shape.SetStart(v(*a));shape.SetEnd(v(*z));shape.SetWidth(mm(.05));b.Add(shape)
# Preliminary mounting pattern. Antenna and under-oscillator keepouts require review.
for x,y in [(4,4),(91,4),(4,81),(91,81)]:
 f=k.FootprintLoad(str(LIB/'MountingHole.pretty'),'MountingHole_3.2mm_M3');f.SetPosition(v(x,y));f.SetReference('H'+str(x)+str(y));b.Add(f)
# Wi-Fi antenna clearance: conservative provisional north rectangle on all copper layers.
z=k.ZONE(b);z.SetIsRuleArea(True);z.SetZoneName('Wi-Fi antenna clearance - confirm module drawing');ls=k.LSET()
for layer in [k.F_Cu,k.In1_Cu,k.In2_Cu,k.B_Cu]:ls.AddLayer(layer)
z.SetLayerSet(ls);z.SetDoNotAllowTracks(True);z.SetDoNotAllowVias(True);z.SetDoNotAllowZoneFills(True);z.SetDoNotAllowPads(False)
o=z.Outline();o.NewOutline()
for x,y in [(37,0),(61,0),(61,8),(37,8)]:o.Append(mm(x),mm(y))
b.Add(z)
t=k.PCB_TEXT(b);t.SetText('PRNboard A - PLACEMENT DRAFT');t.SetPosition(v(48,82));t.SetTextSize(v(1,1));t.SetTextThickness(mm(.15));t.SetLayer(k.F_SilkS);b.Add(t)
k.SaveBoard(str(ROOT/'hardware/prnboard.kicad_pcb'),b)
(ROOT/'validation/footprints.json').write_text(json.dumps(report,indent=2)+'\n')
print('Footprint pin check:',len(report['missing_pads']),'missing,',len(report['unmapped_pads']),'unmapped')
if report['missing_pads'] or report['unmapped_pads']:raise SystemExit(2)
